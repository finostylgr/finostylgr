/** Greek money. 2 → "2€", 1.5 → "1,50€", 2.5 → "2,50€". */
export function formatEuro(amount) {
	const rounded = Math.round(Number(amount) * 100) / 100;
	const text = rounded.toFixed(2).replace('.', ',');
	return (text.endsWith(',00') ? text.slice(0, -3) : text) + '€';
}

function ironingChip() {
	const line = priceLines.find((item) => item.cardChip) ?? priceLines[0];
	return `${formatEuro(line.deliveryPrice)} / ${line.chipPer || line.unit}`;
}

function ironingStoreNote() {
	const bits = priceLines
		.filter((line) => line.storePrice !== line.deliveryPrice)
		.map((line) => `${line.storeLabel || line.title} ${formatEuro(line.storePrice)}`);
	return bits.length ? `Στο κατάστημα σιδερώματος: ${bits.join(', ')}.` : '';
}

function priceChipFor(draft) {
	if (draft.pricingType === 'per_unit') return ironingChip();
	if (draft.pricingType === 'rule') return `Από ${deliveryMinPieces} τεμάχια`;
	return 'Εκτίμηση';
}

export const services = serviceDrafts.map((draft) => {
	const service = {
		...draft,
		priceChip: priceChipFor(draft),
		href: `/ypiresies/${draft.id}/`
	};
	if (draft.pricingType !== 'per_unit') return service;
	return {
		...service,
		unitPrices: priceLines.map((line) => ({
			unit: line.listLabel,
			display: formatEuro(line.deliveryPrice)
		})),
		storeNote: ironingStoreNote()
	};
});

export function getService(id) {
	return services.find((service) => service.id === id);
}

export function relatedServices(service) {
	return (service?.related ?? []).map((id) => getService(id)).filter(Boolean);
}

export function serviceBadges(service) {
	return [
		service.delivery ? `Delivery — από ${deliveryMinPieces} τεμάχια` : 'Μόνο από κατάστημα',
		service.sameDay ? 'Αυθημερόν (έως 12:00, από κατάστημα)' : 'Χρόνος κατόπιν εκτίμησης'
	];
}

