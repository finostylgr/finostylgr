function bubbleField(seed, count, min, max) {
	const out = [];
	let x = seed;
	const rnd = () => {
		x = (x * 1103515245 + 12345) % 2147483648;
		return x / 2147483648;
	};
	for (let i = 0; i < count; i += 1) {
		const size = min + rnd() * (max - min);
		out.push({
			left: `${(rnd() * 104 - 2).toFixed(1)}vw`,
			size: `${size.toFixed(0)}px`,
			dur: `${(22 + rnd() * 26).toFixed(1)}s`,
			delay: `-${(rnd() * 30).toFixed(1)}s`
		});
	}
	return out;
}

